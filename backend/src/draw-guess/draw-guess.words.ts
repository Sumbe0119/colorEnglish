/** Ашиглагдаагүй үгнээс санамсаргүй n ширхэг сонгоно; дутвал бүх үгнээс нөхнө. */
export function pickWords(n: number, used: Set<string>): WordEntry[] {
  const fresh = WORD_BANK.filter((w) => !used.has(w.word));
  const pool = fresh.length >= n ? fresh : WORD_BANK;
  const copy = [...pool];
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy.slice(0, n);
}
